// Helper function to get items by category
export const getItemsByCategory = (category: string): MinecraftItem[] => {
  return minecraftItems.filter(item => item.category === category);
};

// Helper function to get all categories
export const getCategories = (): string[] => {
  return Array.from(new Set(minecraftItems.map(item => item.category))).sort();
};

// Helper function to search items
export const searchItems = (query: string): MinecraftItem[] => {
  const lowerQuery = query.toLowerCase();
  return minecraftItems.filter(item => 
    item.name.toLowerCase().includes(lowerQuery) ||
    item.id.toLowerCase().includes(lowerQuery) ||
    item.category.toLowerCase().includes(lowerQuery)
  );
};

